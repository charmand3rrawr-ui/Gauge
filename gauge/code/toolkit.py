"""Deterministic building blocks for bots: file, text, data and HTTP helpers with no model anywhere.

Bots generated by the Engineer import from here, so the common 80% of a task is already written,
tested and dependency-free. Every function is pure or has an obvious, local side effect.
"""
from __future__ import annotations

