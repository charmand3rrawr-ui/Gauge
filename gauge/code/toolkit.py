from collections.abc import Callable, Iterable
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional


# ---- files -------------------------------------------------------------------------
def read_text(path: str | Path) -> str:
    raw = Path(path).read_bytes()
    for enc in ("utf-8-sig", "utf-8", "cp1252", "latin-1"):
        try:
            return raw.decode(enc)
        except UnicodeDecodeError:
            continue
    return raw.decode("utf-8", errors="replace")


def write_text_atomic(path: str | Path, text: str) -> Path:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_suffix(p.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(p)
    return p


def list_files(folder: str | Path, patterns: Iterable[str] = ("*",), recursive: bool = True) -> list[Path]:
    folder = Path(folder)
    out: list[Path] = []
    for pat in patterns:
        out.extend(folder.rglob(pat) if recursive else folder.glob(pat))
    return sorted({p for p in out if p.is_file()}, key=natural_key)


def natural_key(p: Path | str) -> list:
    s = p.name if isinstance(p, Path) else str(p)
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", s)]


def file_hash(path: str | Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def backup(src: str | Path, dest_dir: str | Path, keep: int = 10) -> Path:
    """Copy a file or folder into dest_dir/<name>-<timestamp>; prune to the newest `keep`."""
    src, dest_dir = Path(src), Path(dest_dir)
    dest_dir.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    dest = dest_dir / f"{src.name}-{stamp}"
    if src.is_dir():
        shutil.copytree(src, dest)
    else:
        shutil.copy2(src, dest)
    olds = sorted([p for p in dest_dir.iterdir() if p.name.startswith(src.name + "-")], key=lambda p: p.name)
    for old in olds[:-keep]:
        shutil.rmtree(old) if old.is_dir() else old.unlink()
    return dest


def watch_folder(folder: str | Path, callback: Callable[[list[Path]], None], interval_s: float = 5.0, patterns: Iterable[str] = ("*",),
                 iterations: Optional[int] = None) -> None:
    """Poll a folder; call callback with files whose mtime changed. No dependencies."""
    seen: dict[Path, float] = {}
    n = 0
    while iterations is None or n < iterations:
        changed = []
        for p in list_files(folder, patterns):
            m = p.stat().st_mtime
            if seen.get(p) != m:
                seen[p] = m
                changed.append(p)
        if changed:
            callback(changed)
        n += 1
        if iterations is None or n < iterations:
            time.sleep(interval_s)


# ---- text -------------------------------------------------------------------------
def word_count(text: str) -> int:
    return len(re.findall(r"\b\w[\w'-]*\b", text))


def text_stats(text: str) -> dict[str, float]:
    words = re.findall(r"\b\w[\w'-]*\b", text)
    sents = [s for s in re.split(r"(?<=[.!?])\s+", text.strip()) if s]
    paras = [p for p in re.split(r"\n\s*\n", text) if p.strip()]
    dialogue = len(re.findall(r"[\"“][^\"”]+[\"”]", text))
    return {"words": len(words), "sentences": len(sents), "paragraphs": len(paras),
            "avg_sentence_words": round(len(words) / max(1, len(sents)), 1), "dialogue_lines": dialogue,
            "reading_minutes": round(len(words) / 240.0, 1)}


def strip_front_matter(text: str) -> str:
    return re.sub(r"^---.*?---\s*", "", text, flags=re.S)


def markdown_to_html(md: str) -> str:
    """Small, predictable Markdown -> HTML for serial sites: headings, paragraphs, em/strong, hr, blockquote."""
    import html

    out = []
    for block in re.split(r"\n\s*\n", strip_front_matter(md).strip()):
        b = block.strip()
        if not b:
            continue
        if re.fullmatch(r"(\*\s*){3,}|-{3,}|_{3,}", b):
            out.append("<hr>")
            continue
        m = re.match(r"^(#{1,6})\s+(.*)$", b)
        if m:
            lvl = len(m.group(1))
            out.append(f"<h{lvl}>{_inline(html.escape(m.group(2)))}</h{lvl}>")
            continue
        if b.startswith(">"):
            inner = " ".join(line.lstrip("> ").strip() for line in b.splitlines())
            out.append(f"<blockquote><p>{_inline(html.escape(inner))}</p></blockquote>")
            continue
        out.append("<p>" + _inline(html.escape(" ".join(line.strip() for line in b.splitlines()))) + "</p>")
    return "\n".join(out)


def _inline(s: str) -> str:
    s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"(?<!\*)\*(?!\*)(.+?)(?<!\*)\*(?!\*)", r"<em>\1</em>", s)
    s = re.sub(r"_(.+?)_", r"<em>\1</em>", s)
    return s


def html_page(title: str, body_html: str) -> str:
    import html

    return ("<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">"
            f"<title>{html.escape(title)}</title><style>body{{max-width:42rem;margin:2rem auto;padding:0 1rem;font:18px/1.6 Georgia,serif}}"
            "p{margin:0 0 1em}@media(prefers-color-scheme:dark){body{background:#111;color:#eee}}</style></head>"
            f"<body><h1>{html.escape(title)}</h1>\n{body_html}\n</body></html>")


# ---- data -------------------------------------------------------------------------
def read_json(path: str | Path, default: Any = None) -> Any:
    p = Path(path)
    if not p.exists():
        return default
    return json.loads(read_text(p))


def write_json(path: str | Path, obj: Any) -> Path:
    return write_text_atomic(path, json.dumps(obj, indent=2, ensure_ascii=False, default=str))


def append_jsonl(path: str | Path, obj: Any) -> None:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    with p.open("a", encoding="utf-8") as f:
        f.write(json.dumps(obj, ensure_ascii=False, default=str) + "\n")


def read_csv(path: str | Path) -> list[dict[str, str]]:
    with open(path, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def write_csv(path: str | Path, rows: list[dict[str, Any]], fieldnames: Optional[list[str]] = None) -> Path:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    fields = fieldnames or (list(rows[0].keys()) if rows else [])
    with p.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for r in rows:
            w.writerow(r)
    return p


def now_iso() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


# ---- http (polite, cached, no model) ------------------------------------------------
def http_get(url: str, cache_dir: Optional[str | Path] = None, max_age_s: int = 3600, timeout: int = 30,
             user_agent: str = "GaugeBot/1 (local automation)") -> str:
    import os

    if os.environ.get("GAUGE_NO_NETWORK"):
        raise PermissionError("this bot runs without network access (set \"network\": true in its manifest if it truly needs it)")
    import requests

    if cache_dir:
        cp = Path(cache_dir) / (hashlib.sha1(url.encode()).hexdigest() + ".cache")
        if cp.exists() and time.time() - cp.stat().st_mtime < max_age_s:
            return cp.read_text(encoding="utf-8")
    r = requests.get(url, headers={"User-Agent": user_agent}, timeout=timeout)
    r.raise_for_status()
    if cache_dir:
        write_text_atomic(cp, r.text)
    return r.text


# ---- processes ----------------------------------------------------------------------
def run(cmd: list[str], cwd: Optional[str | Path] = None, timeout: int = 600) -> tuple[int, str, str]:
    p = subprocess.run(cmd, cwd=str(cwd) if cwd else None, capture_output=True, text=True, timeout=timeout, check=False)
    return p.returncode, p.stdout, p.stderr


def python_exe() -> str:
    return sys.executable
