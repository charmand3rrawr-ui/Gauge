"""A static telemetry dashboard (roadmap item 69): cost by purpose and scores over time, as one HTML file.

No server, no dependencies — it reads the call log and the projects and writes a self-contained page you
open in a browser or drop on a static host. It is a snapshot; regenerate it when you want fresh numbers.
"""
from __future__ import annotations

import html
from pathlib import Path
from typing import Any

_STYLE = """body{font:15px/1.5 system-ui,sans-serif;margin:0;background:#fff;color:#1a1a1a}
@media(prefers-color-scheme:dark){body{background:#141414;color:#e8e8e8}}
.wrap{max-width:820px;margin:0 auto;padding:16px}h1{font-size:1.5rem}h2{font-size:1.1rem;margin-top:24px}
table{border-collapse:collapse;width:100%;font-size:.9rem}td,th{border-bottom:1px solid #8884;padding:6px 8px;text-align:right}
th:first-child,td:first-child{text-align:left}.muted{color:#8888}.bar{height:10px;background:#8a1b1b;border-radius:3px}"""


def _cost_table(rows: list[dict]) -> str:
    if not rows:
        return "<p class=muted>No model calls recorded yet.</p>"
    head = "<tr><th>purpose</th><th>calls</th><th>seconds</th><th>avg s</th><th>prompt tok</th><th>output tok</th><th>failed</th></tr>"
    body = "".join(
        f"<tr><td>{html.escape(r['purpose'])}</td><td>{r['calls']}</td><td>{r['seconds']:.0f}</td>"
        f"<td>{r['avg_seconds']:.1f}</td><td>{r.get('prompt_tokens') or 0}</td>"
        f"<td>{r.get('output_tokens') or 0}</td><td>{r['failed']}</td></tr>" for r in rows)
    return f"<table>{head}{body}</table>"


def _scores_section(projects_dir: Path) -> str:
    from ..write.project import Project
    out = []
    if not projects_dir.exists():
        return ""
    for name in Project.list(projects_dir):
        try:
            p = Project(projects_dir, name)
        except Exception:
            continue
        pts = []
        upto = max(p.state.written, 0)
        if upto == 0:  # state not persisted here; scan the chapter files directly
            n = 1
            while p.read_chapter(n) is not None and n < 10000:
                upto = n
                n += 1
        for n in range(1, upto + 1):
            meta = p.read_meta(n)
            s = meta.get("score")
            if isinstance(s, (int, float)):
                pts.append((n, float(s)))
        if not pts:
            continue
        bars = "".join(
            f'<tr><td>ch{n}</td><td style="width:100%"><div class=bar style="width:{int(s*100)}%"></div></td>'
            f'<td>{s:.2f}</td></tr>' for n, s in pts[-20:])
        avg = sum(s for _, s in pts) / len(pts)
        out.append(f"<h2>{html.escape(name)} <span class=muted>({len(pts)} chapters, mean {avg:.2f})</span></h2>"
                   f"<table>{bars}</table>")
    return "".join(out)


def dashboard_html(db: Any, projects_dir: Path, title: str = "Gauge telemetry") -> str:
    rows = db.call_summary()
    total_calls = sum(r["calls"] for r in rows)
    total_s = sum(r["seconds"] for r in rows)
    return (f"<!doctype html><html lang=en><head><meta charset=utf-8>"
            f"<meta name=viewport content='width=device-width,initial-scale=1'><title>{html.escape(title)}</title>"
            f"<style>{_STYLE}</style></head><body><div class=wrap><h1>{html.escape(title)}</h1>"
            f"<p class=muted>{total_calls} model calls, {total_s:.0f}s in the model.</p>"
            f"<h2>Cost by purpose</h2>{_cost_table(rows)}"
            f"{_scores_section(Path(projects_dir))}"
            f"<p class=muted>Generated by Gauge. A snapshot; regenerate to refresh.</p></div></body></html>")
